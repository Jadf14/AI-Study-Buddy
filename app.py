def grade_for(accuracy: float) -> Dict[str, str]:
    """Map an overall accuracy onto a badge, colour and tone of voice."""
    if accuracy >= 0.9:
        return {"letter": "A", "emoji": "🏆", "color": ACCENT,
                "headline": "Outstanding", "mood": "win"}
    if accuracy >= 0.75:
        return {"letter": "B", "emoji": "🎉", "color": ACCENT,
                "headline": "Strong run", "mood": "win"}
    if accuracy >= 0.5:
        return {"letter": "C", "emoji": "😅", "color": WARN,
                "headline": "Halfway there", "mood": "near"}
    return {"letter": "D", "emoji": "🫠", "color": DANGER,
            "headline": "Rough one", "mood": "rough"}



def _normalise_text(value: str) -> str:
    value = value.lower().strip()
    value = re.sub(r"[^\w\s]", " ", value, flags=re.UNICODE)
    return re.sub(r"\s+", " ", value)


def fallback_short_answer_grade(response: str, q: Dict[str, Any]) -> Dict[str, Any]:
    """Offline concept grader: generous with wording, strict about having the core idea."""
    text = _normalise_text(response)
    if not text:
        return {"correct": False, "score": 0.0, "feedback": tr("no_answer")}
    reference = _normalise_text(str(q.get("answer", "")))
    keywords = [_normalise_text(k) for k in q.get("answer_keywords", []) if _normalise_text(k)]
    reference_words = set(reference.split())
    response_words = set(text.split())
    overlap = len(reference_words & response_words) / max(1, len(reference_words))
    keyword_hits = sum(1 for k in keywords if k in text)
    keyword_ratio = keyword_hits / max(1, len(keywords))
    score = max(overlap, keyword_ratio)
    correct = score >= 0.45 or (keywords and keyword_hits >= max(1, min(2, len(keywords))))
    if correct:
        feedback = tr("nice_answer")
    else:
        feedback = tr("close_answer")
    return {"correct": bool(correct), "score": float(min(1.0, score)), "feedback": feedback}


def evaluate_short_answers_with_claude(api_key: str, course: str, questions: List[Dict[str, Any]], answers: Dict[str, Any]) -> Tuple[Dict[str, Dict[str, Any]], str]:
    typed = [q for q in questions if q.get("type") == "short_answer"]
    if not typed:
        return {}, ""
    fallback = {
        q["id"]: fallback_short_answer_grade(
            str((answers.get(q["id"]) or "")), q)
        for q in typed
    }
    client, err = get_client(api_key)
    if client is None:
        return fallback, tr("offline_detail", detail=err)
    packet = []
    for q in typed:
        raw = answers.get(q["id"], "")
        response = raw.get("response", "") if isinstance(raw, dict) else raw
        packet.append({"id": q["id"], "question": q["question"], "reference_answer": q.get("answer", ""),
                       "keywords": q.get("answer_keywords", []), "student_response": str(response or "")})
    prompt = (
        "Grade these typed answers generously but meaningfully. Focus on whether the student understood the idea, "
        "not exact wording or grammar. A response can be correct when it uses different wording but expresses the same concept. "
        "Return ONLY JSON array with objects containing id, correct (boolean), score (0 to 1), and brief feedback. "
        f"Respond in {st.session_state.get('language', 'English')}. Course: {course}. Learner level: {st.session_state.get('education_level', 'High School')}.\n"
        + json.dumps(packet, ensure_ascii=False)
    )
    try:
        response = client.messages.create(
            model=CLAUDE_MODEL, max_tokens=SHORT_ANSWER_MAX_TOKENS,
            system="You are a fair educational grader. Reward correct ideas even when phrased differently.",
            messages=[{"role": "user", "content": prompt}],
        )
        raw = collect_text(response)
        block = extract_json_array(raw)
        data = json.loads(block) if block else None
        if not isinstance(data, list):
            return fallback, "Claude typed grading returned no usable JSON; offline grading used."
        graded = dict(fallback)
        for item in data:
            if not isinstance(item, dict) or item.get("id") not in graded:
                continue
            graded[item["id"]] = {
                "correct": bool(item.get("correct", False)),
                "score": float(np.clip(float(item.get("score", 0)), 0.0, 1.0)),
                "feedback": str(item.get("feedback", "")).strip()[:500],
            }
        return graded, "Claude graded typed responses by concept, allowing equivalent wording."
    except Exception as exc:
        return fallback, f"Claude typed grading failed ({type(exc).__name__}); offline concept grading used."

def score_quiz(model: Pipeline, api_key: str) -> Dict[str, Any]:
    questions = st.session_state["questions"]
    answers = st.session_state["answers"]
    course = st.session_state["course"]

    elapsed = time.time() - (st.session_state["start_time"] or time.time())
    pace = pace_proxy(elapsed, len(questions))

    short_grades, short_detail = evaluate_short_answers_with_claude(api_key, course, questions, answers)
    st.session_state["short_answer_grading_detail"] = short_detail
    for q in questions:
        if q.get("type") == "short_answer":
            raw = answers.get(q["id"], "")
            response = raw.get("response", "") if isinstance(raw, dict) else raw
            grade = short_grades.get(q["id"], fallback_short_answer_grade(str(response or ""), q))
            answers[q["id"]] = {"response": str(response or ""), **grade}

    n_correct = sum(1 for q in questions if question_is_correct(q, answers))
    overall_accuracy = n_correct / len(questions) if questions else 0.0

    features = build_subtopic_features(questions, answers, pace)
    classified = classify_subtopics(model, features) if not features.empty else pd.DataFrame()
    weak_rows = classified[classified["prediction"] == 1] if not classified.empty else pd.DataFrame()
    any_weakness = not weak_rows.empty
    top = weak_rows.iloc[0] if any_weakness else (classified.iloc[0] if not classified.empty else pd.Series({"subtopic": "General", "weak_probability": 0.0}))
    weak_subtopic = str(top["subtopic"])
    weak_confidence = float(top["weak_probability"])

    missed = [q["question"] for q in questions
              if q["subtopic"] == weak_subtopic and not question_is_correct(q, answers)]

    if any_weakness:
        tips, tips_source, tips_detail = fetch_claude_tips(
            api_key, course, weak_subtopic, missed)
    else:
        tips, tips_source, tips_detail = offline_tips_markdown(weak_subtopic), "offline", ""

    review = []
    for q in questions:
        is_correct = question_is_correct(q, answers)
        raw_answer = answers.get(q["id"])
        if q.get("type") == "short_answer":
            review.append({
                "question": q["question"], "subtopic": q["subtopic"],
                "question_type": "Typed response",
                "your_answer": display_answer(q, raw_answer),
                "correct_answer": q.get("answer", ""),
                "feedback": str(raw_answer.get("feedback", "")) if isinstance(raw_answer, dict) else "",
                "is_correct": is_correct,
            })
        else:
            review.append({
                "question": q["question"], "subtopic": q["subtopic"],
                "question_type": ("Choose all correct" if q.get("type") == "multi_select" else ("Multiple choice" if q.get("type") == "mcq" else "Single choice")),
                "your_answer": display_answer(q, raw_answer),
                "correct_answer": display_answer(q, q.get("answer")),
                "feedback": "", "is_correct": is_correct,
            })

    return {"elapsed": elapsed, "pace": pace, "n_correct": n_correct,
            "n_questions": len(questions), "overall_accuracy": overall_accuracy,
            "classified": classified, "weak_subtopic": weak_subtopic,
            "weak_confidence": weak_confidence, "any_weakness": any_weakness,
            "weak_row": top, "missed_questions": missed, "tips_markdown": tips,
            "tips_source": tips_source, "tips_detail": tips_detail,
            "grade": grade_for(overall_accuracy), "review": review,
            "short_answer_grades": short_grades}


