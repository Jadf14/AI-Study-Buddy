def prepare_local_questions(course: str) -> List[Dict[str, Any]]:
    """Randomly choose 5-10 questions, preferring questions not recently seen."""
    base_source = COURSES.get(course, GENERIC_BANK)
    base = [enrich_question(q, i) for i, q in enumerate(base_source)]
    extra_source = EXTRA_COURSE_QUESTIONS.get(course, EXTRA_GENERIC_QUESTIONS if course not in COURSES else [])
    extra = [enrich_question(q, 100 + i) for i, q in enumerate(extra_source)]
    rotation_source = ROTATION_EXTRA_QUESTIONS.get(course, GENERIC_ROTATION_EXTRA if course not in COURSES else [])
    rotation = [enrich_question(q, 300 + i) for i, q in enumerate(rotation_source)]
    multi = [enrich_question(MULTI_SELECT_EXTRA[course], 900)] if course in MULTI_SELECT_EXTRA else []
    generic_multi = [{"id":"gen_multi", "subtopic":"Applied Problem Solving", "difficulty":2,
        "question":"Which TWO habits usually improve learning quality?",
        "options":["Active recall","Spaced practice","Never checking mistakes","Studying only when exhausted"],
        "answer":[0,1], "type":"multi_select",
        "hint":"Choose the two habits that actively support memory and feedback."}] if course not in COURSES else []
    bank = base + extra + rotation + multi + generic_multi
    target = min(quiz_size(), len(bank))
    seen = st.session_state.get("quiz_history", {}).get(course, set())
    if not isinstance(seen, set):
        seen = set(seen)
    unseen = [q for q in bank if question_signature(q) not in seen]
    pool = unseen if len(unseen) >= target else bank

    short_answers = [q for q in pool if q.get("type") == "short_answer"]
    multi_answers = [q for q in pool if q.get("type") == "multi_select"]
    chosen: List[Dict[str, Any]] = []
    if short_answers:
        chosen.append(random.choice(short_answers))
    if multi_answers and not any(q.get("type") == "multi_select" for q in chosen):
        chosen.append(random.choice(multi_answers))
    remaining = [q for q in pool if q not in chosen]
    chosen.extend(random.sample(remaining, k=min(max(target - len(chosen), 0), len(remaining))))
    random.shuffle(chosen)
    return chosen[:target]


def question_is_correct(q: Dict[str, Any], answers: Dict[str, Any]) -> bool:
    """Evaluate choice, multi-select, and Claude/fallback graded typed responses."""
    value = answers.get(q["id"])
    if q.get("type") == "short_answer":
        return bool(value.get("correct", False)) if isinstance(value, dict) else False
    if q.get("type") == "multi_select":
        if not isinstance(value, (list, tuple, set)):
            return False
        try:
            return sorted(int(x) for x in value) == sorted(int(x) for x in q.get("answer", []))
        except (TypeError, ValueError):
            return False
    return value is not None and value == q.get("answer")


def display_answer(q: Dict[str, Any], answer: Any, include_feedback: bool = False) -> str:
    if q.get("type") == "short_answer":
        if isinstance(answer, dict):
            value = str(answer.get("response") or tr("left_blank"))
            feedback = str(answer.get("feedback") or "").strip()
            return f"{value}{(' — ' + feedback) if include_feedback and feedback else ''}"
        return str(answer or tr("left_blank"))
    if answer is None or answer == []:
        return tr("left_blank")
    if q.get("type") == "multi_select":
        try:
            return ", ".join(str(q["options"][int(i)]) for i in sorted(answer))
        except (KeyError, TypeError, ValueError, IndexError):
            return tr("unrecognized_answer")
    try:
        return str(q["options"][int(answer)])
    except (KeyError, TypeError, ValueError, IndexError):
        return tr("unrecognized_answer")


def _first_present(item: Dict[str, Any], keys: List[str]) -> Any:
    for key in keys:
        if key in item:
            return item[key]
    return None


def coerce_questions(payload: Any) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Convert Claude output into 5-10 usable questions, supporting all interactions."""
    problems: List[str] = []
    if isinstance(payload, dict):
        for key in ("questions", "quiz", "items", "data"):
            if isinstance(payload.get(key), list):
                payload = payload[key]
                break
    if not isinstance(payload, list):
        return [], ["Reply was not a JSON array of questions."]

    cleaned: List[Dict[str, Any]] = []
    for i, item in enumerate(payload):
        if not isinstance(item, dict):
            problems.append(f"Item {i + 1}: not an object.")
            continue
        qtype = str(_first_present(item, ["type", "question_type", "format"]) or "mcq").lower().strip()
        qtype = re.sub(r"[\s-]+", "_", qtype)
        qtype = {
            "short": "short_answer", "typed": "short_answer", "typed_response": "short_answer",
            "open": "short_answer", "open_ended": "short_answer",
            "single": "single_choice", "single_correct": "single_choice", "single_correct_answer": "single_choice",
            "multiple": "multi_select", "multiple_choice": "multi_select", "multiple_correct": "multi_select",
            "multi": "multi_select",
        }.get(qtype, qtype if qtype in {"mcq", "single_choice", "multi_select", "short_answer"} else "mcq")
        question = _first_present(item, ["question", "prompt", "text", "stem"])
        subtopic = _first_present(item, ["subtopic", "sub_topic", "topic", "category"])
        difficulty = _first_present(item, ["difficulty", "level"])
        hint = _first_present(item, ["hint", "clue", "help"])
        if not isinstance(question, str) or not question.strip():
            problems.append(f"Item {i + 1}: missing question text.")
            continue
        try:
            difficulty_int = min(3, max(1, int(difficulty)))
        except (TypeError, ValueError):
            difficulty_int = 2

        if qtype in {"mcq", "single_choice", "multi_select"}:
            options = _first_present(item, ["options", "choices", "answers"])
            raw_answer = _first_present(item, ["answer", "correct_answer", "correct", "correct_option", "answer_index"])
            if isinstance(options, dict):
                options = [options[k] for k in sorted(options)]
            if not isinstance(options, list) or len(options) < 2:
                problems.append(f"Item {i + 1}: missing or unusable options.")
                continue
            options = [str(o).strip() for o in options][:4]
            if qtype == "multi_select":
                answer_list = answer_indices(raw_answer, options)
                if not answer_list or len(answer_list) < 2:
                    problems.append(f"Item {i + 1}: multi-select needs at least two correct options.")
                    continue
                answer_value: Any = answer_list
            else:
                answer_value = resolve_answer_index(raw_answer, options)
                if answer_value is None:
                    problems.append(f"Item {i + 1}: could not resolve the correct answer.")
                    continue
            cleaned.append({
                "id": str(item.get("id") or f"gen_{i}"), "subtopic": str(subtopic).strip() if isinstance(subtopic, str) and subtopic.strip() else "General",
                "difficulty": difficulty_int, "question": question.strip(), "options": options,
                "answer": answer_value, "type": qtype,
                "hint": str(hint).strip() if isinstance(hint, str) and hint.strip() else "Identify the key idea the question is testing.",
            })
            continue

        reference_answer = _first_present(item, ["answer", "reference_answer", "correct_answer", "ideal_answer", "explanation"])
        if not isinstance(reference_answer, str) or not reference_answer.strip():
            problems.append(f"Item {i + 1}: typed-response question has no reference answer.")
            continue
        keywords = _first_present(item, ["answer_keywords", "keywords", "key_points"])
        if not isinstance(keywords, list):
            keywords = []
        cleaned.append({
            "id": str(item.get("id") or f"gen_{i}"), "subtopic": str(subtopic).strip() if isinstance(subtopic, str) and subtopic.strip() else "General",
            "difficulty": difficulty_int, "question": question.strip(), "answer": reference_answer.strip(),
            "answer_keywords": [str(k).strip() for k in keywords if str(k).strip()],
            "type": "short_answer",
            "hint": str(hint).strip() if isinstance(hint, str) and hint.strip() else "Explain the main idea in your own words.",
        })

    seen_text = set()
    unique: List[Dict[str, Any]] = []
    for q in cleaned:
        key = question_signature(q)
        if key in seen_text:
            continue
        seen_text.add(key)
        unique.append(q)
    return unique[:MAX_QUESTIONS], problems


