def extract_json_array(text: str) -> Optional[str]:
    if not text:
        return None
    cleaned = re.sub(r"^\s*```[a-zA-Z]*\s*", "", text.strip())
    cleaned = re.sub(r"```\s*$", "", cleaned).strip()
    start = cleaned.find("[")
    if start == -1:
        return None
    depth, in_string, escaped = 0, False, False
    for i in range(start, len(cleaned)):
        ch = cleaned[i]
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0:
                return cleaned[start:i + 1]
    last_close = cleaned.rfind("}")
    if last_close > start:
        return cleaned[start:last_close + 1] + "]"
    return None


