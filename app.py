def build_synthetic_dataset(n_samples: int = N_SAMPLES, noise: float = LABEL_NOISE,
                            seed: int = 42) -> Tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    accuracy = rng.uniform(0.0, 1.0, n_samples)
    difficulty = rng.uniform(0.0, 1.0, n_samples)
    response_time = rng.uniform(0.0, 1.0, n_samples)
    risk = 2.8 * (1.0 - accuracy) + 0.9 * difficulty + 1.0 * response_time
    labels = (risk > 2.0).astype(int)
    flip = rng.random(n_samples) < noise
    labels = np.where(flip, 1 - labels, labels)
    return np.column_stack([accuracy, difficulty, response_time]), labels


@st.cache_resource(show_spinner=False)
def train_model() -> Tuple[Pipeline, Dict[str, Any]]:
    X, y = build_synthetic_dataset()
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42, stratify=y)
    pipeline = Pipeline([
        ("scaler", StandardScaler()),
        ("clf", LogisticRegression(C=REG_C, max_iter=5000, solver="lbfgs", random_state=42)),
    ])
    pipeline.fit(X_train, y_train)
    cv_scores = cross_val_score(pipeline, X, y, cv=StratifiedKFold(5, shuffle=True, random_state=0))
    predictions = pipeline.predict(X_test)
    tp = int(((predictions == 1) & (y_test == 1)).sum())
    fp = int(((predictions == 1) & (y_test == 0)).sum())
    fn = int(((predictions == 0) & (y_test == 1)).sum())
    tn = int(((predictions == 0) & (y_test == 0)).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    metrics = {
        "train_accuracy": float(pipeline.score(X_train, y_train)),
        "test_accuracy": float(pipeline.score(X_test, y_test)),
        "cv_mean": float(cv_scores.mean()), "cv_std": float(cv_scores.std()),
        "ceiling": 1.0 - LABEL_NOISE, "precision": precision, "recall": recall,
        "confusion": {"tp": tp, "fp": fp, "fn": fn, "tn": tn},
        "n_train": int(len(X_train)), "n_test": int(len(X_test)), "weak_share": float(y.mean()),
    }
    return pipeline, metrics


def raw_feature_weights(pipeline: Pipeline) -> Tuple[np.ndarray, float]:
    scaler: StandardScaler = pipeline.named_steps["scaler"]
    clf: LogisticRegression = pipeline.named_steps["clf"]
    scaled_coef = clf.coef_[0]
    weights = scaled_coef / scaler.scale_
    intercept = float(clf.intercept_[0] - np.sum(scaled_coef * scaler.mean_ / scaler.scale_))
    return weights, intercept


def normalise_difficulty(difficulty: int) -> float:
    return (float(difficulty) - 1.0) / 2.0


def pace_proxy(elapsed_seconds: float, n_questions: int) -> float:
    if n_questions <= 0:
        return 0.5
    return float(np.clip(elapsed_seconds / n_questions / PACE_SATURATION_SECONDS, 0.0, 1.0))


def build_subtopic_features(questions: List[Dict[str, Any]], answers: Dict[str, Any], pace: float) -> pd.DataFrame:
    rows = [{
        "subtopic": q["subtopic"],
        "correct": 1 if question_is_correct(q, answers) else 0,
        "difficulty": normalise_difficulty(q["difficulty"]),
    } for q in questions]
    return (pd.DataFrame(rows).groupby("subtopic", as_index=False)
            .agg(accuracy=("correct", "mean"), difficulty=("difficulty", "mean"),
                 n_questions=("correct", "size"), n_correct=("correct", "sum"))
            .assign(response_time=pace))


def classify_subtopics(model: Pipeline, features: pd.DataFrame) -> pd.DataFrame:
    out = features.copy()
    X = out[FEATURE_NAMES].to_numpy()
    out["prediction"] = model.predict(X)
    out["weak_probability"] = model.predict_proba(X)[:, 1]
    out["status"] = np.where(out["prediction"] == 1, "Weak / Needs Intervention", "Proficient")
    return out.sort_values("weak_probability", ascending=False).reset_index(drop=True)


def explain_row(pipeline: Pipeline, row: pd.Series) -> pd.DataFrame:
    weights, intercept = raw_feature_weights(pipeline)
    records = []
    for name, weight in zip(FEATURE_NAMES, weights):
        value = float(row[name])
        records.append({"Feature": FEATURE_LABELS[name], "Value": round(value, 3),
                        "Weight": round(float(weight), 3), "Contribution": round(float(weight) * value, 3)})
    records.append({"Feature": "Intercept (baseline)", "Value": 1.0,
                    "Weight": round(intercept, 3), "Contribution": round(intercept, 3)})
    return pd.DataFrame(records)


def logodds_to_probability(z: float) -> float:
    return float(1.0 / (1.0 + np.exp(-z)))


