def resolve_answer_index(raw: Any, options: List[str]) -> Optional[int]:
    """Accept numeric indices, A/B/C/D, or exact option text."""
    if isinstance(raw, bool):
        return None
    if isinstance(raw, (int, np.integer)):
        idx = int(raw)
        if 0 <= idx < len(options):
            return idx
        if 1 <= idx <= len(options):
            return idx - 1
        return None
    if isinstance(raw, str):
        value = raw.strip()
        if value.isdigit():
            idx = int(value)
            if 0 <= idx < len(options):
                return idx
            if 1 <= idx <= len(options):
                return idx - 1
        if len(value) == 1 and value.upper().isalpha():
            idx = ord(value.upper()) - 65
            if 0 <= idx < len(options):
                return idx
        for i, option in enumerate(options):
            if str(option).strip().lower() == value.lower():
                return i
    return None

def answer_indices(raw: Any, options: List[str]) -> Optional[List[int]]:
    if isinstance(raw, (list, tuple, set)):
        values = list(raw)
    else:
        values = [raw]
    result = []
    for value in values:
        idx = resolve_answer_index(value, options)
        if idx is None or idx in result:
            continue
        result.append(idx)
    return sorted(result) if result else None



def enrich_question(q: Dict[str, Any], index: int) -> Dict[str, Any]:
    """Return a safe quiz record with an explicit interaction type and a hint."""
    item = dict(q)
    item["id"] = str(item.get("id") or f"q_{index}")
    raw_type = str(item.get("type") or ("short_answer" if "options" not in item else "mcq")).lower().strip()
    raw_type = re.sub(r"[\s-]+", "_", raw_type)
    aliases = {
        "short": "short_answer", "typed": "short_answer", "typed_response": "short_answer",
        "open": "short_answer", "open_ended": "short_answer",
        "single": "single_choice", "single_correct": "single_choice", "single_correct_answer": "single_choice",
        "multiple": "multi_select", "multiple_choice": "multi_select", "multiple_correct": "multi_select",
        "multi": "multi_select", "multi_select": "multi_select",
    }
    item["type"] = aliases.get(raw_type, raw_type if raw_type in {"mcq", "single_choice", "multi_select", "short_answer"} else "mcq")
    item["hint"] = str(item.get("hint") or "Break the question into its key idea and recall the rule or definition behind it.")
    if item["type"] in {"mcq", "single_choice", "multi_select"} and "options" in item:
        item["options"] = [str(o).strip() for o in item["options"]]
        if item["type"] == "multi_select":
            item["answer"] = sorted(set(int(x) for x in item.get("answer", []) if isinstance(x, (int, np.integer))))
    return item


