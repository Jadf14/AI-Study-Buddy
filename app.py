def render_model_explainer(pipeline: Pipeline, metrics: Dict[str, Any]) -> None:
    """The jury-facing explanation of what the classifier is and how it decides."""
    with st.expander("🧠 How the model works (for the judges)"):
        st.markdown(
            "**The question it answers.** For one sub-topic, is this student "
            "*Proficient* (0) or *Weak / Needs Intervention* (1)? That is a binary "
            "classification, which is exactly what logistic regression is built for.")
        st.markdown(
            "**What it looks at.** Three numbers per sub-topic, each squeezed into a "
            "0-to-1 range so no single one dominates by virtue of its units: how much "
            "you got right, how hard those questions were, and how slowly you worked.")

        weights, intercept = raw_feature_weights(pipeline)
        st.dataframe(pd.DataFrame({
            "Feature": [FEATURE_LABELS[f] for f in FEATURE_NAMES],
            "Learned weight": [round(float(w), 3) for w in weights],
            "Pushes toward": ["Proficient" if w < 0 else "Weak" for w in weights],
            "Odds multiplier": [round(float(np.exp(w)), 2) for w in weights],
        }), hide_index=True, use_container_width=True)
        st.caption(f"Baseline intercept: {intercept:.3f}. The odds multiplier is how much "
                   "the odds of being weak change when that feature goes from 0 to 1.")

        st.markdown(
            "**How a score becomes a probability.** Multiply each feature by its "
            "weight, add them up, add the intercept. That total is the log-odds *z*. "
            "The sigmoid, 1 / (1 + e to the minus z), squashes *z* into a probability "
            "between 0 and 1. Above 0.5 the sub-topic is flagged as weak.")

        st.markdown("**Training data.** No real student records were used. "
                    f"{N_SAMPLES:,} synthetic rows were generated from a weighted risk "
                    f"rule, then {LABEL_NOISE:.0%} of the labels were deliberately "
                    "flipped to represent students who defy the pattern.")

        c1, c2, c3 = st.columns(3)
        c1.metric("5-fold CV accuracy", f"{metrics['cv_mean']:.2%}",
                  delta=f"± {metrics['cv_std']:.2%}", delta_color="off")
        c2.metric("Theoretical ceiling", f"{metrics['ceiling']:.0%}",
                  delta="set by label noise", delta_color="off")
        c3.metric("Gap to ceiling",
                  f"{(metrics['ceiling'] - metrics['cv_mean']) * 100:.2f} pts",
                  delta="essentially optimal", delta_color="off")

        st.markdown(
            "**Why not something fancier.** We swept sample size, label noise, "
            "regularisation strength and polynomial feature expansion under 5-fold "
            "cross-validation. Adding squared and interaction terms made it *worse*. "
            "The boundary is genuinely linear, so a linear model sits about a third of "
            "a point from the ceiling. The remaining error is noise we injected on "
            "purpose, not a modelling failure.")

        cm = metrics["confusion"]
        st.dataframe(pd.DataFrame({
            "": ["Actually weak", "Actually proficient"],
            "Predicted weak": [cm["tp"], cm["fp"]],
            "Predicted proficient": [cm["fn"], cm["tn"]],
        }), hide_index=True, use_container_width=True)
        st.caption(f"Held-out set, {metrics['n_test']:,} rows. "
                   f"Precision {metrics['precision']:.1%}, recall {metrics['recall']:.1%}. "
                   "Recall matters most here: missing a struggling student is worse "
                   "than an extra study tip.")


