def ask_tutor_claude(api_key: str, context: str, history: List[Dict[str, str]],
                     user_message: str) -> Tuple[str, str]:
    client, err = get_client(api_key)
    if client is None:
        return tr("api_error"), err

    messages: List[Dict[str, str]] = []
    for item in history[-10:]:
        if item.get("role") in {"user", "assistant"} and item.get("content"):
            messages.append({"role": item["role"], "content": item["content"]})
    messages.append({"role": "user", "content": user_message})
    try:
        response = client.messages.create(
            model=CLAUDE_MODEL,
            max_tokens=CHAT_MAX_TOKENS,
            system=TUTOR_SYSTEM_PROMPT + "\n" + language_instruction() + "\n\nQUIZ CONTEXT:\n" + context,
            messages=messages,
        )
        text = collect_text(response)
        if not text:
            return tr("tutor_empty"), "Claude returned an empty reply."
        return text, ""
    except Exception as exc:  # noqa: BLE001
        return tr("tutor_error"), f"{type(exc).__name__}: {exc}"




def render_tutor_chat(results: Dict[str, Any], api_key: str) -> None:
    """Live end-of-quiz tutor grounded in the exact quiz and answer review."""
    st.markdown(f"#### {tr('chat')}")
    st.caption(tr("chat_caption"))

    for message in st.session_state.get("tutor_messages", []):
        with st.chat_message(message["role"]):
            st.markdown(message["content"])

    prompt = st.chat_input(tr("chat_placeholder"), key="tutor_chat_input")
    if not prompt:
        return

    history = st.session_state.get("tutor_messages", [])
    st.session_state["tutor_messages"] = history + [{"role": "user", "content": prompt}]
    with st.chat_message("user"):
        st.markdown(prompt)

    context = build_tutor_context(results)
    with st.chat_message("assistant"):
        with st.spinner(tr("thinking")):
            reply, detail = ask_tutor_claude(api_key, context, history, prompt)
        st.markdown(reply)
    st.session_state["tutor_messages"].append({"role": "assistant", "content": reply})
    if detail:
        st.caption(translate_plain_text(api_key, detail))


